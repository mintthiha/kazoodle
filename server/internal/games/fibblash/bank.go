// Rules for adding a REAL or HYBRID question:
//   - One defensible answer. If several are true, list every one in accept,
//     or a player's true answer gets treated as a lie.
//   - A source someone can check, and a one-sentence explanation.
//   - A blank, written "____", where the answer goes.
